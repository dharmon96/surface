/** Caller's cue sheet: one row per cue, one column per surface showing what lands (layer:slot) or "hold". */
import ExcelJS from "exceljs";
import type { Cue, ShowDoc } from "../types.js";
import { pad, record } from "../naming.js";

const F = { name: "Arial" };
const FILL = (argb: string) => ({ type: "pattern" as const, pattern: "solid" as const, fgColor: { argb } });

function surfaceCell(c: Cue, surface: string): string {
  const t = c.targets.find((x) => x.surface === surface);
  if (!t) return "hold";
  return t.actions.map((a) => {
    if (a.op === "show") { const b = a.media.behaviour; const tag = b.kind === "timed" ? ` (${b.holdSec}s→${b.then === "revertBase" ? "base" : "clear"})` : b.kind === "playHold" ? " (hold last)" : b.kind === "playToMarker" ? ` (pause @${b.markerSec}s)` : ""; return `${a.layer}: ${a.media.slot}${tag}`; }
    if (a.op === "clear") return `${a.layer}: clear`;
    return `${a.layer}: ${a.key}=${a.value}`;
  }).join("\n");
}

export async function writeCueSheet(doc: ShowDoc, cues: Cue[], path: string): Promise<void> {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Cue Sheet", { views: [{ state: "frozen", ySplit: 4 }], pageSetup: { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0, printTitlesRow: "4:4" } });
  const surfaces = doc.surfaces.filter((s) => cues.some((c) => c.targets.some((t) => t.surface === s.id)));
  const head = ["Cue #", "Group", "Cue", "d3 tag", "Resolume", "Companion", ...surfaces.map((s) => s.name), "Trigger / notes", "Est. time"];
  const ev = doc.event;
  ws.addRow([`${ev.name} — ${ev.venue ?? ""}${ev.city ? ", " + ev.city : ""} — ${ev.date ?? ""}`]); ws.mergeCells(1, 1, 1, head.length); ws.getCell("A1").font = { ...F, bold: true, size: 14 };
  ws.addRow([`Doors ${ev.doors ?? "—"} · ${ev.broadcast?.network ?? ""} feed ${ev.broadcast?.feedStart ?? ""} · Walk order: ${(ev.walkOrder ?? []).join(" then ")} · Generated by Surface from '${doc.source?.file ?? "manual"}'`]); ws.getCell("A2").font = { ...F, italic: true, size: 9, color: { argb: "FF666666" } };
  ws.addRow([]);
  const hr = ws.addRow(head); hr.eachCell((c) => { c.font = { ...F, bold: true, size: 10, color: { argb: "FFFFFFFF" } }; c.fill = FILL("FF1A1C20"); c.alignment = { vertical: "middle", wrapText: true }; });
  let lastGroup: string | null = null;
  for (const c of cues) {
    const b = doc.data.bouts?.find((x: any) => x.id === c.group);
    if (b && b.id !== lastGroup) {
      const red = doc.data.fighters[b.red], blue = doc.data.fighters[b.blue];
      const t = `BOUT ${b.order} · ${b.rounds} RDS · ${(b.weightClass ?? "").toUpperCase()}${b.title ? " · " + b.title.toUpperCase() : ""}   |   RED ${red.name} (${red.country}) ${record(red)}   v   BLUE ${blue.name} (${blue.country}) ${record(blue)}${b.timing ? `   |   walk ${b.timing.walk} · 1st bell ${b.timing.firstBell} · final ${b.timing.finalBell}` : ""}`;
      const r = ws.addRow([t]); ws.mergeCells(r.number, 1, r.number, head.length);
      r.getCell(1).font = { ...F, bold: true, size: 10, color: { argb: "FFFFFFFF" } }; r.getCell(1).fill = FILL(b.isMain ? "FFA8801E" : "FF3A3F4A");
      lastGroup = b.id;
    }
    const res = c.resolume ? (c.resolume.groups === "ALL" ? `col ${c.resolume.column}` : `col ${c.resolume.column} → ${c.resolume.groups.join(",")}`) : "";
    const comp = c.companion ? `P${c.companion.page} ${c.companion.row + 1}/${c.companion.col + 1}` : "";
    const r = ws.addRow([pad(c.n), c.group, c.name, c.d3?.tag ?? "", res, comp, ...surfaces.map((s) => surfaceCell(c, s.id)), c.trigger ?? "", c.timing ?? ""]);
    const variant = c.id.split("_").pop() ?? "";
    const tint = /WALK_|INTRO_|WIN_/.test(c.id) ? ({ RED: "FFF6D5CF", BLUE: "FFD3E0F7", DRAW: "FFF1E6C7" } as Record<string, string>)[variant] : c.group === "EVT" ? "FFEAE8E2" : undefined;
    r.eachCell({ includeEmpty: true }, (cell) => { cell.font = { ...F, size: 9, color: { argb: cell.value === "hold" ? "FF999999" : "FF000000" } }; cell.alignment = { vertical: "top", wrapText: true }; cell.border = { bottom: { style: "thin", color: { argb: "FFD6D3CB" } } }; if (tint) cell.fill = FILL(tint); });
  }
  const widths = [7, 6, 40, 8, 16, 11, ...surfaces.map(() => 34), 34, 9];
  widths.forEach((w, i) => (ws.getColumn(i + 1).width = w));
  const lg = wb.addWorksheet("Legend & Review");
  lg.addRows([["Field", "Meaning"],
    ["Cue #", "Also the Resolume column number. 'Go 87' means the same thing everywhere."],
    ["d3 tag", "disguise CUE tag bout.cue — N.1/N.2 walkouts, N.3/N.4 anthems, N.5/N.6 intros, N.7 fight base, N.11–N.22 rounds, N.90/91/92 winner red/blue/draw, N.95 up next, N.99 hold"],
    ["Surface columns", "LAYER: slot that lands on that surface. BASE loops underneath; OVERLAY sits over the base and is cleared, not re-cued; FULL covers everything while it runs. 'hold' = surface not addressed."],
    ["Behaviours", "(10s→base) = timed overlay reverting to base · (hold last) = plays once, holds last frame (VTs, winners) · (pause @Ns) = plays to marker and pauses (weigh-in scale) · none = loop"],
    ["Slot name", "{GROUP}_{GRAPHIC}[_{VARIANT}]_{SCREEN}_{W}x{H} — the file the designer/promoter must deliver and the slot name in Resolume/disguise."],
    ["Review flags", doc.review.flags.join("; ") || "none"]]);
  lg.getRow(1).font = { ...F, bold: true }; lg.getColumn(1).width = 16; lg.getColumn(2).width = 120;
  lg.eachRow((r) => r.eachCell((c) => { c.font = { ...F, size: 10, bold: r.number === 1 }; c.alignment = { wrapText: true, vertical: "top" }; }));
  await wb.xlsx.writeFile(path);
}
